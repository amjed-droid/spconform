#' Print Method for spconform Objects
#'
#' Displays a concise summary of the conformal prediction object including
#' model type, nominal target coverage, and a preview table of prediction intervals.
#'
#' @param x An object of class \code{"spconform"}.
#' @param ... Further arguments passed to or from other methods.
#'
#' @return Invisibly returns the input object \code{x}.
#' @export
print.spconform <- function(x, ...) {
  cat("<spconform> ", x$type, " conformal prediction\n", sep = "")
  cat(sprintf("Target coverage: %.1f%%\n", 100 * (1 - x$alpha)))
  n <- length(x$pred)
  cat(sprintf("Number of prediction points: %d\n", n))
  if (!is.null(x$anisotropy) && isTRUE(x$anisotropy$is_anisotropic)) {
    cat(sprintf("Spatial anisotropy: Auto-corrected (Ratio = %.2fx along %d deg)\n",
                x$anisotropy$ratio, x$anisotropy$principal_angle))
  }
  k <- min(n, 6)
  df <- data.frame(
    pred = round(x$pred[seq_len(k)], 3),
    lower = round(x$lower[seq_len(k)], 3),
    upper = round(x$upper[seq_len(k)], 3)
  )
  print(df)
  if (n > k) cat(sprintf("... (%d more)\n", n - k))
  invisible(x)
}

#' Summary Method for spconform Objects
#'
#' Computes and displays summary statistics of the prediction interval widths
#' generated by an \code{spconform} object.
#'
#' @param object An object of class \code{"spconform"}.
#' @param ... Further arguments passed to or from other methods.
#'
#' @return Invisibly returns the input object \code{object}.
#' @export
summary.spconform <- function(object, ...) {
  width <- object$upper - object$lower
  cat("spconform summary\n")
  cat("------------------\n")
  cat("Type:              ", object$type, "\n")
  cat("Target coverage:   ", sprintf("%.1f%%", 100 * (1 - object$alpha)), "\n")
  cat("Mean interval width:", round(mean(width), 4), "\n")
  cat("Median interval width:", round(stats::median(width), 4), "\n")
  invisible(object)
}

#' Plot Prediction Intervals for spconform Objects
#'
#' Plots point predictions and conformal prediction intervals across observation
#' indices, optionally overlaying true target values for visual evaluation.
#'
#' @param x An object of class \code{"spconform"}.
#' @param y_true Optional numeric vector of true observed responses at prediction locations.
#' @param ... Further graphical parameters passed to \code{\link[graphics]{plot}}.
#'
#' @return Invisibly returns the input object \code{x}.
#' @importFrom graphics points segments legend
#' @export
plot.spconform <- function(x, y_true = NULL, ...) {
  n <- length(x$pred)
  ord <- seq_len(n)
  
  dots <- list(...)
  xlab_val <- if (!is.null(dots$xlab)) dots$xlab else if (identical(x$type, "areal")) "Areal Unit Index" else "Prediction Index"
  ylab_val <- if (!is.null(dots$ylab)) dots$ylab else "Predicted / Response Value"
  dots$xlab <- NULL
  dots$ylab <- NULL
  
  all_vals <- c(x$pred, x$lower, x$upper)
  if (!is.null(y_true)) all_vals <- c(all_vals, y_true)
  finite_vals <- all_vals[is.finite(all_vals)]
  ylim_val <- if (length(finite_vals) == 0) c(0, 1) else range(finite_vals, na.rm = TRUE)
  pad <- diff(ylim_val) * 0.05
  if (pad == 0) pad <- 0.5
  ylim_val <- c(ylim_val[1] - pad, ylim_val[2] + pad)
  
  plot_args <- c(list(
    x = ord, y = x$pred,
    ylim = ylim_val,
    pch  = 19,
    xlab = xlab_val,
    ylab = ylab_val,
    main = paste0("spconform (", x$type, ") - ", round(100 * (1 - x$alpha)), "% Intervals")
  ), dots)
  do.call(graphics::plot, plot_args)
  
  graphics::segments(ord, x$lower, ord, x$upper, col = "grey50", lwd = 1.2)
  graphics::points(ord, x$pred, pch = 19, col = "black")
  if (!is.null(y_true)) {
    graphics::points(ord, y_true, col = "red", pch = 4, lwd = 1.2)
    graphics::legend(
      "topright",
      legend = c("Prediction", "Conformal Interval", "True Value"),
      col    = c("black", "grey50", "red"),
      pch    = c(19, NA, 4),
      lty    = c(NA, 1, NA),
      lwd    = c(NA, 1.2, 1.2),
      bty    = "n"
    )
  }
  invisible(x)
}

#' Empirical Coverage and Average Interval Width for an spconform Object
#'
#' Evaluates empirical coverage, average prediction interval width,
#' and the strictly proper Winkler interval score for an \code{"spconform"} object.
#'
#' @param object An object of class \code{"spconform"}.
#' @param y_true Numeric vector of true observed values at the prediction
#'   locations, same length/order as \code{object$pred}.
#' @param na.rm Logical; if \code{TRUE}, missing values in \code{y_true} are
#'   removed before computing evaluation metrics. Defaults to \code{TRUE}.
#'
#' @return A named list with:
#'   \item{coverage}{Proportion of observations falling within \code{[lower, upper]}}.
#'   \item{mean_width}{Average prediction interval width}.
#'   \item{winkler_score}{Mean Winkler interval score across evaluation points}.
#'
#' @references
#' Winkler, R. L. (1972). A Decision-Theoretic Approach to Interval Estimation.
#' \emph{Journal of the American Statistical Association}, 67(337), 187--191.
#'
#' @examples
#' set.seed(1)
#' n <- 20
#' adj <- matrix(0, n, n)
#' for (i in 1:(n - 1)) { adj[i, i + 1] <- 1; adj[i + 1, i] <- 1 }
#' y <- cumsum(rnorm(n))
#' out <- scp_areal(y, adjacency = adj, alpha = 0.2)
#' coverage_report(out, y)
#'
#' @export
coverage_report <- function(object, y_true, na.rm = TRUE) {
  # 1. Classification Modality
  if (inherits(object, "spconform_classification")) {
    y_true <- as.character(y_true)
    n <- length(object$prediction_sets)
    if (length(y_true) != n) {
      stop("length(y_true) must equal number of classification predictions.")
    }
    covered <- logical(n)
    for (i in seq_len(n)) {
      covered[i] <- y_true[i] %in% object$prediction_sets[[i]]
    }
    cov_val <- mean(covered, na.rm = na.rm)
    alpha <- object$alpha
    K <- length(object$classes)
    set_sizes <- object$set_sizes

    # Strictly proper Conformal Brier Score for prediction sets
    # Penalizes large set sizes and heavily penalizes miscoverage (2/alpha)
    cbs_vec <- (set_sizes / K) + (2 / alpha) * (!covered)
    brier_score <- mean(cbs_vec, na.rm = na.rm)

    res <- list(
      modality       = "classification",
      nominal        = 1 - alpha,
      coverage       = cov_val,
      coverage_gap   = abs(cov_val - (1 - alpha)),
      avg_set_size   = mean(set_sizes, na.rm = na.rm),
      singleton_rate = mean(set_sizes == 1, na.rm = na.rm),
      brier_score    = brier_score,
      n              = n
    )
    class(res) <- "spconform_coverage_report"
    return(res)
  }

  # 2. Multivariate Ellipsoidal Modality
  if (inherits(object, "spconform_multivariate")) {
    y_true <- as.matrix(y_true)
    m <- nrow(object$pred)
    d <- object$dimension
    if (nrow(y_true) != m || ncol(y_true) != d) {
      stop("y_true dimensions must match object predictions (m x d).")
    }
    multi_rep <- multivariate_coverage_report(object, y_true)
    res <- list(
      modality              = "multivariate",
      nominal               = 1 - object$alpha,
      joint_coverage        = multi_rep$joint_coverage,
      coverage_gap          = abs(multi_rep$joint_coverage - (1 - object$alpha)),
      marginal_coverage     = multi_rep$marginal_coverage,
      mean_ellipsoid_volume = mean(object$ellipsoid_volumes, na.rm = na.rm),
      mean_projected_width  = mean(colMeans(object$upper - object$lower, na.rm = na.rm)),
      n                     = m,
      dimension             = d
    )
    class(res) <- "spconform_coverage_report"
    return(res)
  }

  # 3. Discrete Count Modality
  if (inherits(object, "spconform_count")) {
    y_true <- as.numeric(y_true)
    n <- length(object$pred)
    if (length(y_true) != n) {
      stop("length(y_true) must equal length(object$pred).")
    }
    alpha <- object$alpha
    covered <- (y_true >= object$lower) & (y_true <= object$upper)
    cov_val <- mean(covered, na.rm = na.rm)

    # Discrete integer width: count span [L, U] contains (U - L + 1) discrete states
    span_widths <- (object$upper - object$lower + 1)
    underage <- pmax(0, object$lower - y_true)
    overage  <- pmax(0, y_true - object$upper)
    wis_count <- span_widths + (2 / alpha) * underage + (2 / alpha) * overage

    res <- list(
      modality        = "count",
      nominal         = 1 - alpha,
      coverage        = cov_val,
      coverage_gap    = abs(cov_val - (1 - alpha)),
      mean_span_width = mean(span_widths, na.rm = na.rm),
      winkler_score   = mean(wis_count, na.rm = na.rm),
      zero_lower_rate = mean(object$lower == 0, na.rm = na.rm),
      n               = n
    )
    class(res) <- "spconform_coverage_report"
    return(res)
  }

  # 4. Standard Continuous Geostatistical / Areal Modality
  if (!inherits(object, "spconform")) {
    stop("'object' must be an spconform object (geostatistical, areal, count, multivariate, or classification).")
  }
  y_true <- as.numeric(y_true)
  if (length(y_true) != length(object$pred)) {
    stop("length(y_true) must equal length(object$pred).")
  }
  alpha <- object$alpha
  widths <- object$upper - object$lower
  covered <- (y_true >= object$lower) & (y_true <= object$upper)
  cov_val <- mean(covered, na.rm = na.rm)

  underage <- pmax(0, object$lower - y_true)
  overage  <- pmax(0, y_true - object$upper)
  wis_vec  <- widths + (2 / alpha) * underage + (2 / alpha) * overage

  res <- list(
    modality      = "continuous",
    nominal       = 1 - alpha,
    coverage      = cov_val,
    coverage_gap  = abs(cov_val - (1 - alpha)),
    mean_width    = mean(widths, na.rm = na.rm),
    winkler_score = mean(wis_vec, na.rm = na.rm),
    n             = length(object$pred)
  )
  class(res) <- "spconform_coverage_report"
  res
}

#' Print Method for spconform_coverage_report Objects
#' @param x An object of class \code{"spconform_coverage_report"}.
#' @param ... Additional arguments.
#' @export
print.spconform_coverage_report <- function(x, ...) {
  cat("====================================================\n")
  cat(sprintf("  spconform Coverage & Efficiency Audit (%s)\n", toupper(x$modality)))
  cat("====================================================\n")
  cat(sprintf("  Target Nominal Level : %5.1f%%\n", 100 * x$nominal))

  if (x$modality == "classification") {
    cat(sprintf("  Empirical Coverage   : %5.1f%% (Gap = %+.2f%%)\n", 100 * x$coverage, 100 * (x$coverage - x$nominal)))
    cat(sprintf("  Average Set Size     : %.3f classes\n", x$avg_set_size))
    cat(sprintf("  Singleton Rate       : %5.1f%% (High-confidence points)\n", 100 * x$singleton_rate))
    cat(sprintf("  Conformal Brier Score: %.4f (Strictly Proper)\n", x$brier_score))
  } else if (x$modality == "multivariate") {
    cat(sprintf("  Joint Coverage       : %5.1f%% (Ellipsoidal Containment, Gap = %+.2f%%)\n",
                100 * x$joint_coverage, 100 * (x$joint_coverage - x$nominal)))
    cat(sprintf("  Mean Ellipsoid Volume: %.4f (Dimension d = %d)\n", x$mean_ellipsoid_volume, x$dimension))
    cat(sprintf("  Mean Projected Width : %.4f\n", x$mean_projected_width))
    cat("  Marginal Coverages   :\n")
    for (nm in names(x$marginal_coverage)) {
      cat(sprintf("    - %-12s : %5.1f%%\n", nm, 100 * x$marginal_coverage[nm]))
    }
  } else if (x$modality == "count") {
    cat(sprintf("  Empirical Coverage   : %5.1f%% (Gap = %+.2f%%)\n", 100 * x$coverage, 100 * (x$coverage - x$nominal)))
    cat(sprintf("  Mean Count Span      : %.3f integer states\n", x$mean_span_width))
    cat(sprintf("  Winkler Score (WIS)  : %.4f (Strictly Proper)\n", x$winkler_score))
    cat(sprintf("  Zero-Bounded Rate    : %5.1f%% [L = 0 non-negative bounds]\n", 100 * x$zero_lower_rate))
  } else {
    cat(sprintf("  Empirical Coverage   : %5.1f%% (Gap = %+.2f%%)\n", 100 * x$coverage, 100 * (x$coverage - x$nominal)))
    cat(sprintf("  Mean Interval Width  : %.4f\n", x$mean_width))
    cat(sprintf("  Winkler Score (WIS)  : %.4f (Strictly Proper)\n", x$winkler_score))
  }

  cat(sprintf("  Sample Size Evaluated: %d locations\n", x$n))
  cat("====================================================\n")
  invisible(x)
}

#' Coerce an spconform Object to a Data Frame
#'
#' Converts a conformal prediction output object of class \code{"spconform"}
#' into a tidy \code{data.frame} containing coordinates (if present), point
#' predictions, lower/upper bounds, and interval widths.
#'
#' @param x An object of class \code{"spconform"}.
#' @param row.names \code{NULL} or a character vector giving row names.
#' @param optional Logical; passed to \code{as.data.frame}.
#' @param ... Additional arguments (currently unused).
#'
#' @return A \code{data.frame} with prediction columns \code{pred},
#'   \code{lower}, \code{upper}, \code{width}, and any coordinate columns.
#' @export
as.data.frame.spconform <- function(x, row.names = NULL, optional = FALSE, ...) {
  df <- data.frame(
    pred  = x$pred,
    lower = x$lower,
    upper = x$upper,
    width = x$upper - x$lower
  )
  if (!is.null(x$s0)) {
    coords <- as.data.frame(x$s0)
    if (ncol(coords) == 2 && all(names(coords) %in% c("V1", "V2"))) {
      names(coords) <- c("x", "y")
    }
    df <- cbind(coords, df)
  }
  as.data.frame(df, row.names = row.names, optional = optional, ...)
}

#' Extract Predictions and Intervals from an spconform Object
#'
#' Extracts point predictions or prediction interval bounds from a fitted
#' \code{spconform} object.
#'
#' @param object An object of class \code{"spconform"}.
#' @param interval Character string specifying the type of prediction intervals
#'   to extract: \code{"none"} (default, point predictions only) or
#'   \code{"prediction"} (matrix with fit, lwr, upr).
#' @param ... Further arguments passed to or from other methods.
#'
#' @return If \code{interval = "none"}, a numeric vector of point predictions.
#'   If \code{interval = "prediction"}, a numeric matrix with columns \code{fit},
#'   \code{lwr}, and \code{upr}.
#' @export
predict.spconform <- function(object, interval = c("none", "prediction"), ...) {
  interval <- match.arg(interval)
  if (interval == "none") {
    return(object$pred)
  } else {
    res <- cbind(fit = object$pred, lwr = object$lower, upr = object$upper)
    return(res)
  }
}

#' Extract Residuals from an spconform Object
#'
#' Calculates prediction residuals (observed minus fitted values) or
#' nonconformity scores for an \code{spconform} object given true responses.
#'
#' @param object An object of class \code{"spconform"}.
#' @param y_true Numeric vector of true observed responses at prediction locations.
#' @param type Character string indicating residual type: \code{"response"}
#'   (raw residuals \eqn{y - \hat{y}}) or \code{"abs"} (absolute nonconformity scores
#'   \eqn{|y - \hat{y}|}).
#' @param ... Further arguments passed to or from other methods.
#'
#' @return A numeric vector of residuals.
#' @export
residuals.spconform <- function(object, y_true, type = c("response", "abs"), ...) {
  if (missing(y_true) || is.null(y_true)) {
    stop("Argument 'y_true' must be provided to compute prediction residuals.")
  }
  if (length(y_true) != length(object$pred)) {
    stop("Length of 'y_true' must match the number of predictions.")
  }
  type <- match.arg(type)
  res <- y_true - object$pred
  if (type == "abs") {
    res <- abs(res)
  }
  res
}
